let currentLanguage = 'id';

function applyLanguage(language) {
    const dictionary = translations[language];
    if (!dictionary) {
        return;
    }

    currentLanguage = language;
    document.documentElement.lang = language;
    document.title = metadata[language].title;

    const description = document.querySelector('meta[name="description"]');
    if (description) {
        description.setAttribute('content', metadata[language].description);
    }

    translatableElements.forEach((element) => {
        const translation = dictionary[element.dataset.i18n];
        if (translation) {
            element.textContent = translation;
        }
    });

    languageButtons.forEach((button) => {
        const isActive = button.dataset.language === language;
        button.classList.toggle('is-active', isActive);
        button.setAttribute('aria-pressed', String(isActive));
    });

    whatsappLinks.forEach((link) => {
        link.href = `https://wa.me/6281818173095?text=${encodeURIComponent(whatsappMessages[language])}`;
    });

    if (systemMessage) {
        systemMessage.textContent = language === 'id'
            ? 'strategi → desain → engineering → dampak'
            : 'strategy → design → engineering → impact';
    }

    try {
        window.localStorage.setItem('rnq-language', language);
    } catch {
        // The preference simply stays session-only when storage is unavailable.
    }
}

function getInitialLanguage() {
    try {
        const stored = window.localStorage.getItem('rnq-language');
        if (stored === 'id' || stored === 'en') {
            return stored;
        }
    } catch {
        // Fall back to the page default.
    }

    return 'id';
}

languageButtons.forEach((button) => {
    button.addEventListener('click', () => applyLanguage(button.dataset.language));
});

applyLanguage(getInitialLanguage());

function closeMenu() {
    if (!menuToggle || !mobileMenu) {
        return;
    }

    menuToggle.setAttribute('aria-expanded', 'false');
    mobileMenu.classList.remove('is-open');
    document.body.classList.remove('menu-open');
}

if (menuToggle && mobileMenu) {
    menuToggle.addEventListener('click', () => {
        const open = menuToggle.getAttribute('aria-expanded') === 'true';
        menuToggle.setAttribute('aria-expanded', String(!open));
        mobileMenu.classList.toggle('is-open', !open);
        document.body.classList.toggle('menu-open', !open);
    });

    mobileMenu.querySelectorAll('a').forEach((link) => {
        link.addEventListener('click', closeMenu);
    });

    window.addEventListener('resize', () => {
        if (window.innerWidth > 960) {
            closeMenu();
        }
    });
}

function updateScrollState() {
    const scrollTop = window.scrollY;
    const scrollable = document.documentElement.scrollHeight - window.innerHeight;
    const progress = scrollable > 0 ? scrollTop / scrollable : 0;

    document.documentElement.style.setProperty('--scroll', Math.min(progress, 1));
    header?.classList.toggle('is-scrolled', scrollTop > 24);
}

updateScrollState();
window.addEventListener('scroll', updateScrollState, { passive: true });

const revealElements = document.querySelectorAll('.reveal');

if ('IntersectionObserver' in window && !reduceMotion) {
    const revealObserver = new IntersectionObserver((entries, observer) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                entry.target.classList.add('is-visible');
                observer.unobserve(entry.target);
            }
        });
    }, {
        threshold: 0.12,
        rootMargin: '0px 0px -40px',
    });

    revealElements.forEach((element) => revealObserver.observe(element));
} else {
    revealElements.forEach((element) => element.classList.add('is-visible'));
}

const finePointer = window.matchMedia('(hover: hover) and (pointer: fine)').matches;

if (finePointer && !reduceMotion) {
    document.body.classList.add('has-pointer');

    window.addEventListener('pointermove', (event) => {
        document.documentElement.style.setProperty('--cursor-x', `${event.clientX}px`);
        document.documentElement.style.setProperty('--cursor-y', `${event.clientY}px`);
    }, { passive: true });

    document.querySelectorAll('[data-tilt]').forEach((element) => {
        element.addEventListener('pointermove', (event) => {
            const bounds = element.getBoundingClientRect();
            const x = (event.clientX - bounds.left) / bounds.width;
            const y = (event.clientY - bounds.top) / bounds.height;
            const rotateX = (0.5 - y) * 4;
            const rotateY = (x - 0.5) * 4;

            element.style.transform = `perspective(900px) rotateX(${rotateX}deg) rotateY(${rotateY}deg)`;
            element.style.setProperty('--card-x', `${x * 100}%`);
            element.style.setProperty('--card-y', `${y * 100}%`);
        });

        element.addEventListener('pointerleave', () => {
            element.style.transform = '';
        });
    });

    document.querySelectorAll('.magnetic').forEach((element) => {
        element.addEventListener('pointermove', (event) => {
            const bounds = element.getBoundingClientRect();
            const x = event.clientX - bounds.left - bounds.width / 2;
            const y = event.clientY - bounds.top - bounds.height / 2;
            element.style.transform = `translate(${x * 0.08}px, ${y * 0.12}px)`;
        });

        element.addEventListener('pointerleave', () => {
            element.style.transform = '';
        });
    });
}

document.querySelectorAll('.faq-item').forEach((item) => {
    item.addEventListener('toggle', () => {
        if (!item.open) {
            return;
        }

        document.querySelectorAll('.faq-item[open]').forEach((openItem) => {
            if (openItem !== item) {
                openItem.removeAttribute('open');
            }
        });
    });
});

window.addEventListener('storage', (event) => {
    if (event.key === 'rnq-language' && event.newValue && event.newValue !== currentLanguage) {
        applyLanguage(event.newValue);
    }
});
